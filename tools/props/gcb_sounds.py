def bank(n):
    """띠 가르개: rfft 칸마다 띠 무게(띠 x 칸, 제곱 합이 F_MIN..F_MAX 에서 1). 경계는 로그 주파수에서 1/8 옥타브 안팎으로 코사인 넘김"""
    lf = np.log2(np.maximum(np.fft.rfftfreq(n, 1 / RATE), 1e-3))
    le = np.log2(F_MIN * 2.0 ** (np.arange(int(round(np.log2(F_MAX / F_MIN) * BPO)) + 1) / BPO))
    up = [np.sin(np.pi / 2 * np.clip((lf - (e - 0.125)) / 0.25, 0, 1)) for e in le]
    return [up[k] * np.sqrt(1 - up[k + 1] ** 2) for k in range(len(le) - 1)]


def render(spec, seed, dur=None):
    """표 하나 → 표본(크기는 표 그대로). dur 초까지만 만들 수 있다"""
    n = int(min(spec["dur"], dur or 1e9) * RATE)
    t = np.arange(n) / RATE
    X = np.fft.rfft(np.random.default_rng(seed).standard_normal(n))
    out = np.zeros(n)
    for w, comps in zip(bank(n), spec["noise"]):
        if not comps:
            continue
        env = np.zeros(n)
        for d, a, tau, shape in comps:
            u = np.maximum(t - d / 1000, 0)
            env += np.where(t >= d / 1000, a * np.exp(-(u / (tau / 1000)) ** shape) * np.minimum(1, u / RISE), 0.0) ** 2
        y = np.fft.irfft(X * w, n)
        y = y / np.sqrt((y ** 2).mean()) * np.sqrt(env)
        # 띠 에너지를 표의 값(곡선의 넓이)에 맞춘다: 좁은 띠의 짧은 터짐은 잡음 한 번의 우연에 따라 에너지가 크게 달라지므로(씨앗마다 몇 dB)
        out += y * np.clip(np.sqrt(env.sum() / max((y ** 2).sum(), 1e-30)), 0.5, 2.0)
    for d, f0, f1, glide, a, tau, ph in spec["tones"]:
        u, g = np.maximum(t - d / 1000, 0), glide / 1000
        out += np.where(t >= d / 1000, a * np.exp(-u / (tau / 1000)) * np.cos(2 * np.pi * (f1 * u + (f0 - f1) * g * (1 - np.exp(-u / g))) + ph), 0.0)
    return out


def make(name, seed=SEEDS[0]):
    """팩에 넣을 꼴: 자르고 끝을 줄이고 크기를 맞춘 float32 모노"""
    trim, fade, level = PACK.get(name, (None, 0.03, None))
    x = render(SOUNDS[name], seed, trim)
    k = min(len(x), int(fade * RATE))
    x[len(x) - k:] *= np.linspace(1, 0, k)
    peak = np.abs(x).max()
    if level is None:
        return (x * 10 ** (PART_PEAK / 20) / peak).astype(np.float32)
    g = 10 ** (level / 20) / np.sqrt((x[:int(0.25 * RATE)] ** 2).mean())
    return (x * min(g, 10 ** (-1 / 20) / peak)).astype(np.float32)


def fire(key):
    """그 총의 총소리 변형들"""
    return [make(f"{key}.fire", s) for s in SEEDS]


def parts(key):
    """그 총의 부품 소리 {부품 이름: 표본}"""
    return {n.split(".")[1]: make(n) for n in SOUNDS if n.startswith(key + ".") and not n.endswith(".fire")}


def write_ogg(x, path):
    import imageio_ffmpeg
    subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), "-y", "-hide_banner", "-loglevel", "error", "-f", "f32le", "-ar", str(RATE), "-ac", "1", "-i", "-",
                    "-c:a", "libvorbis", "-q:a", "7", "-map_metadata", "-1", "-fflags", "+bitexact", "-flags:a", "+bitexact", str(path)],
                   input=np.asarray(x, "<f4").tobytes(), check=True)  # bitexact: ogg 일련번호를 고정해 같은 표본이면 같은 바이트(팩 sha1 이 안 바뀜)


def write_wav(x, path):
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())


def burst(key, rps, shots, seed=1):
    """게임에서처럼 이어 쏜 소리: 초당 rps 발, 발마다 변형을 무작위로 고르고 높이를 0.96~1.04 로 흔든다(Guns.fire 와 같게)"""
    rng = np.random.default_rng(seed)
    var = fire(key)
    out = np.zeros(int((shots / rps + 1.2) * RATE))
    for i in range(shots):
        x = var[rng.integers(len(var))]
        p = rng.uniform(0.96, 1.04)
        y = np.interp(np.arange(int(len(x) / p)) * p, np.arange(len(x)), x)
        a = int(i / rps * RATE)
        out[a:a + len(y)] += y
    return out / max(1.0, np.abs(out).max())


def check():
    """자체 검사: 표의 모든 소리가 만들어지고, 같은 씨앗이면 같은 표본이고, 값이 -1..1 안"""
    assert SOUNDS, "표가 비었다"
    for name in SOUNDS:
        a, b = make(name), make(name)
        assert np.array_equal(a, b) and np.isfinite(a).all() and np.abs(a).max() <= 1.0, name
    for key in sorted({n.split(".")[0] for n in SOUNDS}):
        assert len(fire(key)) == len(SEEDS), key


def preview(folder):
    """미리듣기 wav: 총소리 변형, 부품 소리, 연사(배율은 tools/props/build_gcb.py GUNS 의 제안값 기준)"""
    folder.mkdir(parents=True, exist_ok=True)
    for key, rps, shots in (("gcb_mastiff", 1.2 * 1.19, 4), ("gcb_rampage", 12 * 0.82, 14), ("gcb_boltpistol", 2.6 * 1.2, 6)):
        for i, x in enumerate(fire(key), 1):
            write_wav(x, folder / f"{key}_fire{i}.wav")
        for part, x in parts(key).items():
            write_wav(x, folder / f"{key}_{part}.wav")
        write_wav(burst(key, rps, shots), folder / f"{key}_연사_초당{rps:.1f}발.wav")
    print(f"미리듣기 {len(list(folder.glob('*.wav')))} 파일 → {folder}")


