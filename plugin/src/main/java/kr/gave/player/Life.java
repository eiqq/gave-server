package kr.gave.player;

/** 사람 상태. 바닐라 죽음과 관전 모드는 쓰지 않는다. */
public enum Life {
    /** 대기실. */
    LOBBY,
    /** 서서 싸움. */
    ALIVE,
    /** 체력 0: 바닥에 눕고 출혈, 동료가 돕기 3초로 일으킴. */
    DOWNED,
    /** 출혈이 끝남: 웨이브 끝까지 지켜보다 쉬는 시간 첫 틱에 상점 앞에서 공짜 부활(재화 손실 없음, 원정은 라운드 중 꺼내기도). */
    DEAD,
    /** 게이브에게 먹힘: 그 개체를 잡으면 상점 앞에서 부활. */
    TRAPPED,
    /** 판 중간에 들어와 다음 웨이브를 기다림. */
    WAITING
}
